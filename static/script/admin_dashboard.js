function openTab(evt, tabName) {
    var i, tabcontent, tablinks;
    tabcontent = document.getElementsByClassName("tab-content");
    for (i = 0; i < tabcontent.length; i++) {
        tabcontent[i].style.display = "none";
    }
    tablinks = document.getElementsByClassName("tab-btn");
    for (i = 0; i < tablinks.length; i++) {
        tablinks[i].className = tablinks[i].className.replace(" active", "");
    }
    
    // Safety check in case tabName is malformed or missing
    var targetTab = document.getElementById(tabName);
    if (targetTab) {
        targetTab.style.display = "block";
        if (evt) {
            evt.currentTarget.className += " active";
        } else {
            var targetBtn = document.getElementById("btn-" + tabName);
            if (targetBtn) targetBtn.className += " active";
        }
    }
}

// Read the window variable generated by the HTML wrapper template
window.onload = function() {
    var activeTab = window.serverActiveTab || "ManageLessons";
    
    // If Jinja didn't render it correctly or it's raw text, fallback safely
    if (activeTab.includes("{") || activeTab === "") {
        activeTab = "ManageLessons";
    }
    
    openTab(null, activeTab);
};

